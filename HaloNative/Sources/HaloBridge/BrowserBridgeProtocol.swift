import Foundation

/// Security and framing bounds for the Chromium Native Messaging bridge foundation.
public enum BrowserBridgeLimits {
    /// Supported protocol version. Any message with a mismatched version is rejected.
    public static let currentProtocolVersion: UInt32 = 1

    /// Maximum wire payload size in bytes (1 MB). Oversized messages are dropped immediately.
    public static let maxMessageSizeBytes: Int = 1_048_576

    /// Maximum length for string properties (e.g. titles, element labels) to prevent memory exhaustion.
    public static let maxStringLength: Int = 32_768

    /// Maximum number of observed interactive/structural elements per snapshot.
    public static let maxElementsPerObservation: Int = 200

    /// Maximum approved text for one Phase 5B.2 text entry (UTF-16 units).
    public static let maxTypedTextLength: Int = 4_000

    /// Required length for cryptographically random session nonces (32 bytes / 64 hex characters).
    public static let nonceLengthHexChars: Int = 64

    /// Per-session state bounds. A peer exceeding either bound is rejected and the
    /// transport should close the session rather than accumulating unbounded state.
    public static let maxOutstandingRequests: Int = 128
    public static let maxTrackedRequestIDs: Int = 4_096
}

