/// Wire framing and serialization utilities enforcing strict limits.
private enum BridgeModelValidation {
    static func boundedUTF8(_ value: String, max: Int, field: String, allowEmpty: Bool = false) throws {
        guard (allowEmpty || !value.isEmpty), value.utf8.count <= max else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Invalid UTF-8 length for \(field).")
        }
    }

    static func nonce(_ value: String, field: String) throws {
        guard value.utf8.count == BrowserBridgeLimits.nonceLengthHexChars,
              value.utf8.allSatisfy({ ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102) }) else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "\(field) must be 32 lowercase hexadecimal bytes.")
        }
    }

    static func browser(_ value: BrowserIdentity) throws {
        try boundedUTF8(value.bundleID, max: 128, field: "browser.bundleID")
        try boundedUTF8(value.sessionID, max: 128, field: "browser.sessionID")
        guard value.pid > 0 else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Browser PID must be positive.") }
    }

    static func tab(_ value: TabGenerationIdentity) throws {
        try browser(value.browser)
        guard value.tabID >= 0, value.documentGenerationID > 0 else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Invalid tab or document generation identity.")
        }
        guard !value.isIncognito else {
            throw BridgeErrorDetails(code: .tabNotAuthorized, message: "Incognito tabs are strictly forbidden from bridge observation.")
        }
        try boundedUTF8(value.url, max: BrowserBridgeLimits.maxStringLength, field: "tab.url")
        try boundedUTF8(value.domain, max: 256, field: "tab.domain")
        guard let url = URL(string: value.url), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
              url.host?.lowercased() == value.domain else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Tab URL and domain are inconsistent.")
        }
    }

    static func request(_ value: BridgeRequest) throws {
        try boundedUTF8(value.requestID, max: 64, field: "requestID")
        try nonce(value.sessionNonce, field: "sessionNonce")
        // Each action carries exactly its own payload fields and nothing else.
        let hasElement = value.elementID != nil || value.expectedElement != nil
        let payloads = (text: value.text != nil, option: value.option != nil, scroll: value.scroll != nil, url: value.url != nil)
        func forbidPayloads(except allowed: String? = nil) throws {
            let present = [("text", payloads.text), ("option", payloads.option), ("scroll", payloads.scroll), ("url", payloads.url)]
                .filter { $0.1 && $0.0 != allowed }
            guard present.isEmpty else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Request type forbids \(present.map(\.0).joined(separator: ", ")).")
            }
        }
        func requireElement() throws {
            guard let elementID = value.elementID, let expected = value.expectedElement else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Element action requires a target tab, element, and expected fingerprint.")
            }
            try elementReference(elementID)
            try boundedUTF8(expected.tagName, max: 128, field: "expectedElement.tagName")
            try boundedUTF8(expected.role, max: 128, field: "expectedElement.role", allowEmpty: true)
            try boundedUTF8(expected.label, max: BrowserBridgeLimits.maxStringLength, field: "expectedElement.label", allowEmpty: true)
            if let kind = expected.kind, BridgeClickKind(rawValue: kind) == nil {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Unknown approved click kind.")
            }
            if let destination = expected.destination { try navigationURL(destination) }
        }
        if value.type != .pauseTabs {
            guard let target = value.targetTab else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Request type requires a target tab.") }
            try tab(target)
        }
        switch value.type {
        case .observeTab, .revokeTab:
            guard !hasElement else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Request type forbids element fields.") }
            try forbidPayloads()
        case .pauseTabs:
            guard value.targetTab == nil, !hasElement else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Request type forbids a target tab.")
            }
            try forbidPayloads()
        case .clickElement:
            try requireElement()
            try forbidPayloads()
        case .typeText:
            try requireElement()
            try forbidPayloads(except: "text")
            guard let text = value.text else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Text entry requires text.") }
            try typedText(text)
        case .selectOption:
            try requireElement()
            try forbidPayloads(except: "option")
            guard let option = value.option else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Selection requires an option.") }
            try boundedUTF8(option, max: 200, field: "option")
        case .scrollTab:
            // The page itself (no element) or one observed scrollable element.
            if hasElement { try requireElement() }
            try forbidPayloads(except: "scroll")
            guard let scroll = value.scroll, (1...20).contains(scroll.amount) else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Scroll requires a direction and 1–20 steps.")
            }
        case .navigateTab:
            guard !hasElement else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Navigation forbids element fields.") }
            try forbidPayloads(except: "url")
            guard let url = value.url else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Navigation requires a URL.") }
            try navigationURL(url)
        }
    }

    /// Navigation targets are absolute http(s) URLs with a host, no embedded
    /// credentials, at most 2,048 bytes.
    static func navigationURL(_ value: String) throws {
        guard value.utf8.count <= 2_048, let components = URLComponents(string: value),
              let scheme = components.scheme?.lowercased(), ["http", "https"].contains(scheme),
              let host = components.host, !host.isEmpty, components.user == nil, components.password == nil,
              !value.unicodeScalars.contains(where: { $0.properties.generalCategory == .control || $0 == " " }) else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Navigation URL must be an absolute http(s) URL without credentials.")
        }
    }

    /// Typed text is 1–4,000 UTF-16 units with no control characters, so it can
    /// never press Enter, Tab, or any other key that submits or navigates.
    static func typedText(_ value: String) throws {
        guard !value.isEmpty, value.utf16.count <= BrowserBridgeLimits.maxTypedTextLength,
              !value.unicodeScalars.contains(where: { $0.properties.generalCategory == .control
                  || $0.value == 0x2028 || $0.value == 0x2029 }) else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Typed text must be 1–4,000 characters without line breaks or control characters.")
        }
    }

    /// Element references are opaque extension-issued tokens: `el_` plus
    /// lowercase alphanumerics, underscores, or hyphens, at most 128 bytes.
    static func elementReference(_ value: String) throws {
        guard value.hasPrefix("el_"), value.utf8.count <= 128,
              value.utf8.allSatisfy({ ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 122) || $0 == 95 || $0 == 45 }) else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Invalid element reference.")
        }
    }

    static func element(_ value: ObservedDOMElement) throws {
        try boundedUTF8(value.elementID, max: 256, field: "element.elementID")
        try boundedUTF8(value.tagName, max: 128, field: "element.tagName")
        try boundedUTF8(value.role, max: 128, field: "element.role", allowEmpty: true)
        try boundedUTF8(value.label, max: BrowserBridgeLimits.maxStringLength, field: "element.label", allowEmpty: true)
        if let kind = value.actionKind, BridgeClickKind(rawValue: kind) == nil {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Unknown element action kind.")
        }
        if let reason = value.blockedReason, BridgeBlockedReason(rawValue: reason) == nil {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Unknown blocked reason.")
        }
        guard value.actionKind == nil || value.blockedReason == nil else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "An element cannot be both actionable and blocked.")
        }
        if let destination = value.destinationURL { try boundedUTF8(destination, max: 2_048, field: "element.destinationURL") }
        if let fields = value.formFields {
            guard fields.count <= 30 else { throw BridgeErrorDetails(code: .oversizedPayload, message: "Too many form fields.") }
            for field in fields {
                try elementReference(field.elementID)
                try boundedUTF8(field.label, max: 200, field: "formField.label", allowEmpty: true)
            }
        }
        if let options = value.options {
            guard options.count <= 100 else { throw BridgeErrorDetails(code: .oversizedPayload, message: "Too many select options.") }
            try options.forEach { try boundedUTF8($0, max: 200, field: "element.option", allowEmpty: true) }
        }
        let values = [value.bounds.x, value.bounds.y, value.bounds.width, value.bounds.height]
        guard values.allSatisfy(\.isFinite), value.bounds.width >= 0, value.bounds.height >= 0 else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Element bounds must be finite with nonnegative dimensions.")
        }
    }

    static func response(_ value: BridgeResponse) throws {
        try boundedUTF8(value.requestID, max: 64, field: "response.requestID")
        try nonce(value.sessionNonce, field: "response.sessionNonce")
        let payloadCount = [value.error != nil, value.handshake != nil, value.observation != nil, value.navigation != nil,
                            value.tabClosed != nil, value.tabAnnouncement != nil, value.actionResult != nil].filter { $0 }.count
        guard value.success ? (value.error == nil && payloadCount <= 1) : (value.error != nil && payloadCount == 1) else {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Response success, error, and payload fields are inconsistent.")
        }
        if let observation = value.observation {
            try tab(observation.tab)
            try boundedUTF8(observation.title, max: BrowserBridgeLimits.maxStringLength, field: "observation.title", allowEmpty: true)
            guard observation.elements.count <= BrowserBridgeLimits.maxElementsPerObservation else {
                throw BridgeErrorDetails(code: .oversizedPayload, message: "Observation contains too many elements.")
            }
            try observation.elements.forEach(element)
        }
        if let nav = value.navigation {
            try browser(nav.browser)
            guard nav.tabID >= 0, nav.previousDocumentGenerationID > 0,
                  nav.newDocumentGenerationID > nav.previousDocumentGenerationID else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Navigation generation identity is invalid.")
            }
            try boundedUTF8(nav.newURL, max: BrowserBridgeLimits.maxStringLength, field: "navigation.newURL")
            try boundedUTF8(nav.newDomain, max: 256, field: "navigation.newDomain")
            guard let url = URL(string: nav.newURL), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
                  url.host?.lowercased() == nav.newDomain.lowercased() else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Navigation URL and domain are inconsistent.")
            }
        }
        if let closed = value.tabClosed {
            try browser(closed.browser)
            guard closed.tabID >= 0, closed.documentGenerationID > 0 else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Tab-close identity is invalid.")
            }
        }
        if let announcement = value.tabAnnouncement {
            guard announcement.tabID >= 0, announcement.documentGenerationID > 0, !announcement.isIncognito else {
                throw BridgeErrorDetails(code: .tabNotAuthorized, message: "Announced tab is invalid or incognito.")
            }
            try boundedUTF8(announcement.title, max: BrowserBridgeLimits.maxStringLength, field: "announcement.title", allowEmpty: true)
            try boundedUTF8(announcement.url, max: BrowserBridgeLimits.maxStringLength, field: "announcement.url")
            try boundedUTF8(announcement.domain, max: 256, field: "announcement.domain")
            guard let url = URL(string: announcement.url), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
                  url.host?.lowercased() == announcement.domain else {
                throw BridgeErrorDetails(code: .payloadMalformed, message: "Announced tab URL and domain are inconsistent.")
            }
        }
        if let error = value.error {
            try boundedUTF8(error.message, max: 1_024, field: "error.message")
        }
        if let action = value.actionResult {
            try tab(action.tab)
            try elementReference(action.elementID)
        }
        if let handshake = value.handshake {
            try nonce(handshake.serverNonce, field: "handshake.serverNonce")
            try nonce(handshake.clientNonce, field: "handshake.clientNonce")
            try boundedUTF8(handshake.extensionID, max: 128, field: "handshake.extensionID")
        }
    }
}

public enum BridgeMessageFraming {
    /// Encodes a typed JSON payload. Native Messaging wire framing is added by `encodeFrame`.
    public static func encode<T: Encodable>(_ message: T) throws -> Data {
        if let request = message as? BridgeRequest { try BridgeModelValidation.request(request) }
        if let response = message as? BridgeResponse { try BridgeModelValidation.response(response) }
        if let observation = message as? TabObservedEvent {
            guard observation.elements.count <= BrowserBridgeLimits.maxElementsPerObservation else {
                throw BridgeErrorDetails(code: .oversizedPayload, message: "Observation contains too many elements.")
            }
        }
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        let data = try encoder.encode(message)
        guard data.count <= BrowserBridgeLimits.maxMessageSizeBytes else {
            throw BridgeErrorDetails(code: .oversizedPayload, message: "Encoded frame size (\(data.count) bytes) exceeds maximum limit of \(BrowserBridgeLimits.maxMessageSizeBytes) bytes.")
        }
        return data
    }

    /// Decodes a message from UTF-8 JSON data after verifying length bounds.
    public static func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T {
        guard data.count <= BrowserBridgeLimits.maxMessageSizeBytes else {
            throw BridgeErrorDetails(code: .oversizedPayload, message: "Payload size (\(data.count) bytes) exceeds maximum limit of \(BrowserBridgeLimits.maxMessageSizeBytes) bytes.")
        }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        do {
            if type == BridgeRequest.self || type == BridgeResponse.self {
                guard let object = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                    throw BridgeErrorDetails(code: .payloadMalformed, message: "Bridge envelope must be a JSON object.")
                }
                let allowed: Set<String> = type == BridgeRequest.self
                    ? ["requestID", "protocolVersion", "sessionNonce", "type", "targetTab", "elementID", "expectedElement", "text", "option", "scroll", "url"]
                    : ["requestID", "protocolVersion", "sessionNonce", "success", "error", "handshake", "observation", "navigation", "tabClosed", "tabAnnouncement", "actionResult"]
                guard Set(object.keys).isSubset(of: allowed) else {
                    throw BridgeErrorDetails(code: .payloadMalformed, message: "Bridge envelope contains unknown fields.")
                }
            }
            let decoded = try decoder.decode(type, from: data)
            if let request = decoded as? BridgeRequest { try BridgeModelValidation.request(request) }
            if let response = decoded as? BridgeResponse { try BridgeModelValidation.response(response) }
            return decoded
        } catch let error as BridgeErrorDetails {
            throw error
        } catch {
            throw BridgeErrorDetails(code: .payloadMalformed, message: "Failed to decode payload: \(error.localizedDescription)")
        }
    }

    /// Chromium Native Messaging uses a four-byte little-endian payload length on macOS.
    public static func encodeFrame<T: Encodable>(_ message: T) throws -> Data {
        let payload = try encode(message)
        var length = UInt32(payload.count).littleEndian
        var frame = withUnsafeBytes(of: &length) { Data($0) }
        frame.append(payload)
        return frame
    }

    public static func decodeFrame<T: Decodable>(_ type: T.Type, from frame: Data) throws -> T {
        guard frame.count >= 4 else { throw BridgeErrorDetails(code: .payloadMalformed, message: "Native Messaging frame is missing its length prefix.") }
        let declared = frame.prefix(4).enumerated().reduce(UInt32(0)) { partial, pair in
            partial | (UInt32(pair.element) << UInt32(pair.offset * 8))
        }
        guard declared <= UInt32(BrowserBridgeLimits.maxMessageSizeBytes), frame.count == Int(declared) + 4 else {
            throw BridgeErrorDetails(code: declared > UInt32(BrowserBridgeLimits.maxMessageSizeBytes) ? .oversizedPayload : .payloadMalformed,
                                     message: "Native Messaging frame length does not match its payload.")
        }
        return try decode(type, from: frame.dropFirst(4))
    }
}

/// Transport-neutral session validation logic for channel-binding nonces, replay defense,
/// document generation freshness, and access pause/revoke state.
/// Pure Swift actor; does not use @unchecked Sendable.
public actor BridgeSessionValidator {
    private struct TabKey: Sendable, Hashable {
        let browser: BrowserIdentity
        let tabID: Int
    }
    private struct PendingRequest: Sendable {
        let target: TabGenerationIdentity?
        let epoch: UInt64
        let navigationEpoch: UInt64
        let expectsNavigation: Bool
    }

    private let expectedSessionNonce: String
    private var seenRequestIDs = Set<String>()
    private var pendingRequests: [String: PendingRequest] = [:]
    private var completedResponseIDs = Set<String>()
    private var activeDocumentGenerations: [TabKey: UInt64] = [:]
    private var isPaused = false
    private var authorizedTabs = Set<TabKey>()
    private var accessEpoch: UInt64 = 0
    /// Counts only navigation events, so a navigation request can tell its own
    /// navigation apart from a pause, revoke, or close in flight.
    private var navigationEpoch: UInt64 = 0

    public init(sessionNonce: String) {
        self.expectedSessionNonce = sessionNonce
    }

    /// Content-independent comparison for fixed-length channel-binding nonces.
    public static func constantTimeEquals(_ a: String, _ b: String) -> Bool {
        let aBytes = Array(a.utf8)
        let bBytes = Array(b.utf8)
        guard aBytes.count == bBytes.count else { return false }
        var difference: UInt8 = 0
        for i in 0..<aBytes.count {
            difference |= aBytes[i] ^ bBytes[i]
        }
        return difference == 0
    }

    public func setPaused(_ paused: Bool) {
        guard isPaused != paused else { return }
        isPaused = paused
        accessEpoch &+= 1
    }

    public func authorizeTab(_ tab: TabGenerationIdentity) throws {
        try BridgeModelValidation.tab(tab)
        let key = TabKey(browser: tab.browser, tabID: tab.tabID)
        authorizedTabs.insert(key)
        activeDocumentGenerations[key] = tab.documentGenerationID
    }

    public func revokeTab(_ tab: TabGenerationIdentity) {
        let key = TabKey(browser: tab.browser, tabID: tab.tabID)
        authorizedTabs.remove(key)
        activeDocumentGenerations.removeValue(forKey: key)
        accessEpoch &+= 1
    }

    public func notifyNavigation(event: TabNavigationEvent) throws {
        try BridgeModelValidation.browser(event.browser)
        let key = TabKey(browser: event.browser, tabID: event.tabID)
        guard authorizedTabs.contains(key),
              activeDocumentGenerations[key] == event.previousDocumentGenerationID,
              event.newDocumentGenerationID > event.previousDocumentGenerationID else {
            throw BridgeErrorDetails(code: .staleDocumentGeneration, message: "Navigation event does not advance the authorized document generation.")
        }
        activeDocumentGenerations[key] = event.newDocumentGenerationID
        accessEpoch &+= 1
        navigationEpoch &+= 1
    }

    public func notifyClosed(event: TabClosedEvent) throws {
        try BridgeModelValidation.browser(event.browser)
        let key = TabKey(browser: event.browser, tabID: event.tabID)
        guard authorizedTabs.contains(key), activeDocumentGenerations[key] == event.documentGenerationID else {
            throw BridgeErrorDetails(code: .staleDocumentGeneration, message: "Tab-close event does not match an authorized document generation.")
        }
        authorizedTabs.remove(key)
        activeDocumentGenerations.removeValue(forKey: key)
        accessEpoch &+= 1
    }

    /// Validates an incoming request against protocol version, session nonce, and replay cache.
    public func validateRequest(_ request: BridgeRequest) throws {
        guard !isPaused else {
            throw BridgeErrorDetails(code: .accessPaused, message: "Bridge access is currently paused.")
        }
        guard request.protocolVersion == BrowserBridgeLimits.currentProtocolVersion else {
            throw BridgeErrorDetails(code: .unsupportedVersion, message: "Protocol version \(request.protocolVersion) is unsupported (expected \(BrowserBridgeLimits.currentProtocolVersion)).")
        }
        guard Self.constantTimeEquals(request.sessionNonce, expectedSessionNonce) else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "Session nonce mismatch.")
        }
        guard !seenRequestIDs.contains(request.requestID) else {
            throw BridgeErrorDetails(code: .replayedRequest, message: "Replayed request ID '\(request.requestID)'.")
        }
        try BridgeModelValidation.request(request)
        guard seenRequestIDs.count < BrowserBridgeLimits.maxTrackedRequestIDs,
              pendingRequests.count < BrowserBridgeLimits.maxOutstandingRequests else {
            throw BridgeErrorDetails(code: .oversizedPayload, message: "Bridge session request-state limit exceeded.")
        }

        if let target = request.targetTab {
            let key = TabKey(browser: target.browser, tabID: target.tabID)
            guard authorizedTabs.contains(key) else {
                throw BridgeErrorDetails(code: .tabNotAuthorized, message: "Tab \(target.tabID) is not authorized.")
            }
            guard let currentGen = activeDocumentGenerations[key], currentGen == target.documentGenerationID else {
                throw BridgeErrorDetails(code: .staleDocumentGeneration, message: "Tab \(target.tabID) document generation \(target.documentGenerationID) is stale (current: \(activeDocumentGenerations[key] ?? 0)).")
            }
        }
        seenRequestIDs.insert(request.requestID)
        pendingRequests[request.requestID] = PendingRequest(target: request.targetTab, epoch: accessEpoch,
                                                            navigationEpoch: navigationEpoch,
                                                            expectsNavigation: request.type == .navigateTab || request.type == .clickElement)
    }

    /// Validates an incoming response against session nonce and pause status.
    public func validateResponse(_ response: BridgeResponse) throws {
        guard !isPaused else {
            throw BridgeErrorDetails(code: .accessPaused, message: "Bridge access changed while the response was in flight.")
        }
        guard response.protocolVersion == BrowserBridgeLimits.currentProtocolVersion else {
            throw BridgeErrorDetails(code: .unsupportedVersion, message: "Response protocol version mismatch.")
        }
        guard Self.constantTimeEquals(response.sessionNonce, expectedSessionNonce) else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "Response session nonce mismatch.")
        }
        try BridgeModelValidation.response(response)
        guard !completedResponseIDs.contains(response.requestID),
              let pending = pendingRequests.removeValue(forKey: response.requestID) else {
            throw BridgeErrorDetails(code: .replayedRequest, message: "Response does not match one outstanding request.")
        }
        // Any access change in flight invalidates the response, except that a
        // navigation request's result survives navigation events (only).
        let changes = accessEpoch &- pending.epoch
        let navigations = navigationEpoch &- pending.navigationEpoch
        guard changes == 0 || (pending.expectsNavigation && changes == navigations) else {
            throw BridgeErrorDetails(code: .accessPaused, message: "Bridge access changed while the response was in flight.")
        }
        completedResponseIDs.insert(response.requestID)
        if let action = response.actionResult {
            guard pending.target == action.tab else {
                throw BridgeErrorDetails(code: .browserMismatch, message: "Action result identity differs from its request.")
            }
        }
        if let obs = response.observation {
            guard pending.target == obs.tab else {
                throw BridgeErrorDetails(code: .browserMismatch, message: "Response identity differs from its request.")
            }
            let key = TabKey(browser: obs.tab.browser, tabID: obs.tab.tabID)
            guard authorizedTabs.contains(key) else {
                throw BridgeErrorDetails(code: .tabNotAuthorized, message: "Response returned data for unauthorized tab \(obs.tab.tabID).")
            }
            guard let currentGen = activeDocumentGenerations[key], currentGen == obs.tab.documentGenerationID else {
                throw BridgeErrorDetails(code: .staleDocumentGeneration, message: "Response returned data for stale document generation \(obs.tab.documentGenerationID).")
            }
        }
    }
}
