/// Validates channel binding after Chromium has authenticated the extension through
/// the native-host manifest's exact `allowed_origins`. A nonce is freshness/channel
/// binding, not a substitute for that browser-enforced peer identity.
public enum BridgeHandshakeValidator {
    public static func validate(challenge: BridgeHandshakeChallenge, response: BridgeHandshakeResponse,
                                 pinnedExtensionID: String, now: Date = Date()) throws {
        guard challenge.version == BrowserBridgeLimits.currentProtocolVersion,
              response.version == BrowserBridgeLimits.currentProtocolVersion else {
            throw BridgeErrorDetails(code: .unsupportedVersion, message: "Handshake protocol version mismatch.")
        }
        try BridgeModelValidation.nonce(challenge.serverNonce, field: "serverNonce")
        try BridgeModelValidation.nonce(response.serverNonce, field: "response.serverNonce")
        try BridgeModelValidation.nonce(response.clientNonce, field: "clientNonce")
        // The client must contribute its own entropy; echoing the server nonce
        // proves nothing about the responder.
        guard !BridgeSessionValidator.constantTimeEquals(response.clientNonce, challenge.serverNonce) else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "Handshake clientNonce must not echo serverNonce.")
        }
        guard BridgeSessionValidator.constantTimeEquals(challenge.serverNonce, response.serverNonce),
              response.extensionID == pinnedExtensionID else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "Handshake channel binding or pinned extension identity mismatch.")
        }
        guard abs(now.timeIntervalSince(challenge.issuedAt)) <= 30,
              response.acceptedAt >= challenge.issuedAt,
              response.acceptedAt.timeIntervalSince(challenge.issuedAt) <= 30 else {
            throw BridgeErrorDetails(code: .authenticationFailed, message: "Handshake freshness window expired.")
        }
    }
}

