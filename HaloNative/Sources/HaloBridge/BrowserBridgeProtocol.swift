/// Semantic DOM element observed in an authorized tab.
/// Ephemeral elementIDs are opaque tokens generated by the content script and bound
/// strictly to the documentGenerationID. Password/sensitive fields are flagged as protected.
public struct ObservedDOMElement: Sendable, Codable, Equatable {
    public let elementID: String
    public let tagName: String
    public let role: String
    public let label: String
    public let isProtected: Bool
    public let isEnabled: Bool
    public let bounds: BoundedRect
    /// Set by the extension when the element passes the Phase 5B.1 click policy:
    /// a plain button outside any form or link, enabled, visible, not protected.
    /// Halo re-checks its own policy; this flag alone never authorizes a click.
    public let isActionable: Bool?
    /// Set by the extension when the element passes the Phase 5B.2 text-entry
    /// policy: an enabled, editable, visible plain text field that is not a
    /// password, one-time-code, or payment field. Halo re-checks its own policy.
    public let isEditable: Bool?
    /// Phase 5B.3: a single-choice `<select>` eligible for option selection.
    public let isSelectable: Bool?
    /// Phase 5B.3: an element whose content scrolls.
    public let isScrollable: Bool?
    /// Phase 5B.3: enabled option labels of a selectable `<select>` (bounded).
    public let options: [String]?
    /// Phase 5B.4: what clicking this element would do (`BridgeClickKind`), or nil.
    public let actionKind: String?
    /// Phase 5B.4: why clicking is blocked (`BridgeBlockedReason`), or nil.
    public let blockedReason: String?
    /// Phase 5B.4: where a link or form submission goes (absolute URL).
    public let destinationURL: String?
    /// Phase 5B.4: the fields a submit button would send.
    public let formFields: [BridgeFormField]?

    public init(elementID: String, tagName: String, role: String, label: String, isProtected: Bool, isEnabled: Bool,
                bounds: BoundedRect, isActionable: Bool? = nil, isEditable: Bool? = nil,
                isSelectable: Bool? = nil, isScrollable: Bool? = nil, options: [String]? = nil,
                actionKind: String? = nil, blockedReason: String? = nil, destinationURL: String? = nil,
                formFields: [BridgeFormField]? = nil) {
        self.elementID = elementID
        self.tagName = tagName.lowercased()
        self.role = role.lowercased()
        self.label = label
        self.isProtected = isProtected
        self.isEnabled = isEnabled
        self.bounds = bounds
        self.isActionable = isActionable
        self.isEditable = isEditable
        self.isSelectable = isSelectable
        self.isScrollable = isScrollable
        self.options = options
        self.actionKind = actionKind
        self.blockedReason = blockedReason
        self.destinationURL = destinationURL
        self.formFields = formFields
    }
}

